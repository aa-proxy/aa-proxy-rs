//! MTP protocol constants.
//!
//! Ported near-verbatim from the AAWireless-rs POC (`mtp_constants.rs`),
//! with permission from its author. Most of these enum variants are never
//! constructed by [`crate::mtp::mtp_server`] — they exist so that
//! [`crate::mtp::mtp_packet::MtpHeader::try_from`] can parse *any* code a
//! head unit sends without erroring out (an unsupported operation just
//! gets `MtpResponse::OperationNotSupported`, not a parse failure that
//! would kill the whole MTP stage).

#![allow(dead_code)]

